#!/usr/bin/env node
// Headless-прогон учебной программы (карта tutorial): станция в node, за оператора — виртуальная консоль, как в act1-check.
// Сценарий: тело без датчиков → описание → лидар из свёртка у старта → по поворотам тоннеля (потолок, несущая до конца) →
// ящик в дальнем зале: вскрыть, взять камеру → кадр назад, на пройденный путь.
//   node tools/tutorial-check.js [seed=N] [тихо]
if(!process.argv.some(a=>/^map=/.test(a))) process.argv.push('map=tutorial');
const {run,act,until,skip,go,fail,report,st,oc,notes}=require('./op-harness.js').harness();

function scenario(){
  run('станция: статус',/симуляция:/,20,'паспорт со строкой симуляции');
  skip(5);
  run('М: лидар',/лидар не установлен|ничего не произошло/,20,'без лидара снимок не идёт');
  run('М: описание',/свёрток/,60,'свёрток в описании');
  run('М: изучить свёрток',/лидар/,90,'в свёртке лидар');
  run('М: взять лидар из свёртка',/взял: лидар/,60,'лидар взят');
  run('М: лидар',/лидар \(снято/,30,'лидар после взятия снимает');
  run('М: лидар',/сплошное/,30,'стены тоннеля на лидаре');
  // по поворотам оси (terrain.tunnel.segs) — человек ведёт так же, по стенам с лидара
  for(const [xy,what] of [['40 0','поворот 1'],['40 24','поворот 2'],['64 24','поворот 3'],['64 6','поворот 4'],['88 6','зал']]) if(!go(xy,'по тоннелю: '+what,300)) return;
  if(!go('95 7.5','к ящику',300)) return;
  run('М: описание',/ящик/,60,'ящик в описании');
  run('М: вскрыть ящик',/вскрыл/,60,'ящик вскрыт');
  run('М: взять камеру из ящика',/взял: камера/,60,'камера взята');
  act('М: смотреть 64 6'); skip(3);   // взгляд назад, на поворот 4
  run('М: кадр 32',/кадр.*32×32|32×32/,120,'кадр 32×32 назад дошёл');
}
try{ scenario(); }catch(e){ fail('сценарий: '+e.message); }
const d=st.snapshot(), u=d.units[0];
if(u&&!u.carrier) fail('у ящика нет несущей');
if(u&&!u.sensors.camera) fail('камеры на теле нет');
report('лидар → тоннель → камера → кадр назад', `М1 (${u.x.toFixed(0)},${u.y.toFixed(0)})${u.alive?'':' мёртв'}${u.sensors.camera?' с камерой':''}; заметок мира ${notes.length}`);
